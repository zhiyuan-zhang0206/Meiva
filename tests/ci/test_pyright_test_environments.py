def _without_region(text: str) -> str:
    return text[: text.index(gen.BEGIN)] + text[text.index(gen.END) :]


def _generated_roots(text: str) -> list[str]:
    region = text[text.index(gen.BEGIN) : text.index(gen.END)]
    return [line.split('"')[1] for line in region.splitlines() if line.startswith("root = ")]


