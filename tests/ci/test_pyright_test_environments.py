def test_an_environment_root_that_exists_names_a_directory(environment: dict[str, Any]) -> None:
    """A stale root (a directory that moved or was deleted) configures nothing."""
    assert (_REPO_ROOT / environment["root"]).is_dir(), environment["root"]


_SYNTHETIC_PYPROJECT = f"""\
[tool.pytest.ini_options]
testpaths = ["tests", "gateway/**/tests", "base/**/tests", "meiva_builtins/**/tests"]

[tool.pyright]
{chr(10).join(f'{rule} = "error"' for rule in _SEVEN)}

{gen.BEGIN}
{gen.END}

[[tool.pyright.executionEnvironments]]
root = "gateway/routers"
reportAny = "error"
reportExplicitAny = "error"

[[tool.pyright.executionEnvironments]]
root = "meiva_builtins/skills/integrations/web-ai"
extraPaths = ["meiva_builtins/skills/integrations/web-ai/scripts"]
reportAny = "error"
reportExplicitAny = "error"
"""

_OWING = ("gateway/routers", "meiva_builtins/skills/integrations/web-ai")


def _without_region(text: str) -> str:
    return text[: text.index(gen.BEGIN)] + text[text.index(gen.END) :]


def _generated_roots(text: str) -> list[str]:
    region = text[text.index(gen.BEGIN) : text.index(gen.END)]
    return [line.split('"')[1] for line in region.splitlines() if line.startswith("root = ")]


def test_tests_roots_are_the_outermost_tests_directory_of_a_package_module() -> None:
    # meiva:note
    # The nested `tests/tests`, the top-level `tests/`, `docs/tests` (not a pytest host) and
    # `attests` (not a tests directory) are not roots.
    assert gen.tests_roots(
        [
            "gateway/routers/tests/test_a.py",
            "gateway/routers/tests/area/test_b.py",
            "gateway/routers/tests/tests/test_c.py",
            "meiva_builtins/skills/integrations/gmail/scripts/tests/test_gmail.py",
            "tests/components/base/test_top.py",
            "docs/tests/test_x.py",
            "gateway/routers/attests/x.py",
            "gateway/routers/mod.py",
        ],
        pytest_test_hosts(_SYNTHETIC_PYPROJECT),
    ) == ["gateway/routers/tests", "meiva_builtins/skills/integrations/gmail/scripts/tests"]


def test_an_entry_is_written_only_for_tests_under_a_root_that_owes_any() -> None:
    # meiva:note
    # `gateway/agents` and `base/x` have no covering entry, so their tests follow the global rules.
    tracked = [
        "gateway/routers/tests/test_a.py",
        "gateway/agents/tests/test_b.py",
        "base/x/tests/test_c.py",
        "meiva_builtins/skills/integrations/web-ai/scripts/tests/test_w.py",
    ]
    text = gen.generate(_SYNTHETIC_PYPROJECT, tracked, owing_any=_OWING)
    assert _generated_roots(text) == [
        "gateway/routers/tests",
        "meiva_builtins/skills/integrations/web-ai/scripts/tests",
    ]
    region = text[text.index(gen.BEGIN) : text.index(gen.END)]
    assert (
        'root = "meiva_builtins/skills/integrations/web-ai/scripts/tests"\n'
        'extraPaths = ["meiva_builtins/skills/integrations/web-ai/scripts"]\n\n'
    ) in region
    assert 'root = "gateway/routers/tests"\n\n' in region
    assert "reportAny" not in region
    assert "reportExplicitAny" not in region
    config = tomllib.loads(text)["tool"]["pyright"]
    assert gen.covering_environment(config, "gateway/routers/tests") == {
        "root": "gateway/routers/tests"
    }
    assert set(_rules(config, "gateway/routers/tests").values()) == {"error"}
    assert gen.covering_environment(config, "gateway/routers")["reportAny"] == "error"


def test_a_root_that_does_not_owe_any_holds_its_tests_to_the_entry() -> None:
    held = gen.generate(_SYNTHETIC_PYPROJECT, ["gateway/routers/tests/test_a.py"], owing_any=())
    assert _generated_roots(held) == []
    assert held == _SYNTHETIC_PYPROJECT


def test_generating_twice_changes_nothing_and_the_output_is_sorted() -> None:
    tracked = [
        "meiva_builtins/skills/integrations/web-ai/scripts/tests/test_a.py",
        "gateway/routers/tests/test_a.py",
    ]
    once = gen.generate(_SYNTHETIC_PYPROJECT, tracked, owing_any=_OWING)
    assert gen.generate(once, tracked, owing_any=_OWING) == once
    assert gen.generate(once, list(reversed(tracked)), owing_any=_OWING) == once
    roots = _generated_roots(once)
    assert roots == sorted(roots)


def test_a_region_marker_that_is_missing_or_repeated_stops_the_generator() -> None:
    with pytest.raises(SystemExit, match="exactly one generated region"):
        gen.generate(_SYNTHETIC_PYPROJECT.replace(gen.END, ""), [])
    with pytest.raises(SystemExit, match="exactly one generated region"):
        gen.generate(_SYNTHETIC_PYPROJECT + gen.BEGIN + "\n" + gen.END + "\n", [])
    with pytest.raises(SystemExit, match="out of order"):
        swapped = _SYNTHETIC_PYPROJECT.replace(gen.BEGIN, "@@").replace(gen.END, gen.BEGIN)
        gen.generate(swapped.replace("@@", gen.END), [])


class _Checkout:
    """A scratch git repository holding the synthetic pyproject.toml and its tests modules."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.pyproject = root / "pyproject.toml"
        self._git("init", "-q")
        self.pyproject.write_text(_SYNTHETIC_PYPROJECT, encoding="utf-8")

    def _git(self, *args: str) -> None:
        subprocess.run(  # noqa: S603
            [
                "env",
                "-u",
                "GIT_DIR",
                "-u",
                "GIT_WORK_TREE",
                "-u",
                "GIT_INDEX_FILE",
                "-u",
                "GIT_COMMON_DIR",
                "git",
                "-C",
                str(self.root),
                *args,
            ],
            check=True,
            capture_output=True,
        )

    def add(self, rel: str) -> None:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("def test_x() -> None:\n    pass\n", encoding="utf-8")
        self._git("add", rel)

    def remove(self, rel: str) -> None:
        self._git("rm", "-q", "-f", rel)

    def check(self) -> int:
        return gen.main(["--check"], repo_root=self.root, owing_any=_OWING)

    def regenerate(self) -> int:
        return gen.main([], repo_root=self.root, owing_any=_OWING)

    def roots(self) -> list[str]:
        return _generated_roots(self.pyproject.read_text())


@pytest.fixture
def checkout(tmp_path: Path) -> _Checkout:
    return _Checkout(tmp_path)


def test_moving_a_tests_directory_makes_the_check_fail_until_the_generator_runs(
    checkout: _Checkout,
) -> None:
    checkout.add("gateway/routers/tests/test_a.py")
    assert checkout.check() == 1
    assert checkout.regenerate() == 0
    assert checkout.check() == 0
    assert checkout.roots() == ["gateway/routers/tests"]

    # meiva:note
    # A test moves into another owing root: the region is stale until the script runs.
    checkout.add("meiva_builtins/skills/integrations/web-ai/scripts/tests/test_b.py")
    assert checkout.check() == 1
    assert checkout.roots() == ["gateway/routers/tests"]  # --check writes nothing
    assert checkout.regenerate() == 0
    assert checkout.check() == 0
    assert checkout.roots() == [
        "gateway/routers/tests",
        "meiva_builtins/skills/integrations/web-ai/scripts/tests",
    ]


def test_the_generator_changes_nothing_outside_the_fenced_region(checkout: _Checkout) -> None:
    handwritten = _without_region(checkout.pyproject.read_text())
    checkout.add("gateway/routers/tests/test_a.py")
    checkout.add("base/x/tests/test_b.py")
    assert checkout.regenerate() == 0
    assert _without_region(checkout.pyproject.read_text()) == handwritten


def test_a_pure_deletion_makes_the_region_stale_too(checkout: _Checkout) -> None:
    """The case a `files:`-filtered pre-commit hook never sees, hence the pre-push family."""
    checkout.add("gateway/routers/tests/test_a.py")
    checkout.add("meiva_builtins/skills/integrations/web-ai/scripts/tests/test_b.py")
    assert checkout.regenerate() == 0
    checkout.remove("meiva_builtins/skills/integrations/web-ai/scripts/tests/test_b.py")
    assert checkout.check() == 1
    assert checkout.regenerate() == 0
    assert checkout.roots() == ["gateway/routers/tests"]
