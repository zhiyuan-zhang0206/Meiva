# meiva:note
# Tests directories follow the global pyright rules, except under a root that owes Any debt.
#
# pyright configures by directory: an `executionEnvironments` entry names a root directory (no
# globs) and the first entry, in list order, whose root contains a file decides that file's rules.
# The seven `reportUnknown*`/`reportMissing*` rules are global errors, so every file, tests
# included, is held to them. A hand-written directory entry that also holds `reportAny` /
# `reportExplicitAny` would hold the tests under its root to those rules as well, so a root whose
# tests still owe Any debt is listed in `TESTS_OWING_ANY` and each tests directory under it gets
# a generated entry of its own, listed before the covering entry, that carries no Any rule.
# Those entries are generated by `scripts/codegen/gen_pyright_test_environments.py` into a fenced
# region of pyproject.toml; the tests at the end pin the generator.
#

from __future__ import annotations

import subprocess
import tomllib
from pathlib import Path
from typing import Any

import pytest

from meizel.roles import pytest_test_hosts
from scripts.codegen import gen_pyright_test_environments as gen

_REPO_ROOT = Path(__file__).resolve().parents[2]
_PYPROJECT_TEXT = (_REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8")
_PYRIGHT = tomllib.loads(_PYPROJECT_TEXT)["tool"]["pyright"]
_SEVEN = (
    "reportUnknownMemberType",
    "reportUnknownArgumentType",
    "reportUnknownVariableType",
    "reportUnknownParameterType",
    "reportMissingParameterType",
    "reportUnknownLambdaType",
    "reportMissingTypeArgument",
)


def _rules(config: dict[str, Any], directory: str) -> dict[str, Any]:
    environment = gen.covering_environment(config, directory)
    return {rule: environment.get(rule, config.get(rule)) for rule in _SEVEN}


def test_the_real_configuration_holds_all_seven_rules_at_error_globally() -> None:
    assert {rule: _PYRIGHT.get(rule) for rule in _SEVEN} == dict.fromkeys(_SEVEN, "error")


def _tracked_test_directories() -> list[str]:
    result = subprocess.run(  # noqa: S603 - fixed git query in this repository
        ["git", "-C", str(_REPO_ROOT), "ls-files", "-z", "--", "*.py"],
        capture_output=True,
        text=True,
        check=True,
    )
    hosts = frozenset(pytest_test_hosts(_PYPROJECT_TEXT))
    directories = {
        path.rsplit("/", 1)[0]
        for path in result.stdout.split("\0")
        if (parts := path.split("/"))[0] in hosts and "tests" in parts[:-1]
    }
    return sorted(directories)


def test_every_tests_directory_is_held_to_the_seven_rules_at_error() -> None:
    weak = {
        directory: rules
        for directory in _tracked_test_directories()
        if set((rules := _rules(_PYRIGHT, directory)).values()) != {"error"}
    }
    assert not weak, f"these test directories are not type-checked at error: {sorted(weak)}"


