# meiva:note
# Tests directories follow the global pyright rules, except tests that owe Any debt.
#
# pyright configures by directory: an `executionEnvironments` entry names a root directory (no
# globs) and the first entry, in list order, whose root contains a file decides that file's rules.
# The seven `reportUnknown*`/`reportMissing*` rules are global errors, so every file, tests
# included, is held to them. A hand-written directory entry that also holds `reportAny` /
# `reportExplicitAny` would hold the tests under its root to those rules as well, so the path prefix
# of tests that still owe Any debt is listed in `scripts/codegen/pyright_tests_owing_any.txt` and
# each tests directory under it whose covering entry holds the Any rules gets a generated entry of
# its own, listed before the covering entry, that carries no Any rule.
# Those entries are generated by `scripts/codegen/gen_pyright_test_environments.py` into a fenced
# region of pyproject.toml; the tests at the end pin the generator.
#

