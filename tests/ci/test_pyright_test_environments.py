class _Checkout:
    """A scratch git repository holding the synthetic pyproject.toml and its tests modules."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.pyproject = root / "pyproject.toml"
        _git(root, "init", "-q")
        self.pyproject.write_text(_SYNTHETIC_PYPROJECT, encoding="utf-8")
        self.owe()

    def owe(self, *prefixes: str) -> None:
        data = self.root / gen.OWING_ANY_FILE
        data.parent.mkdir(parents=True, exist_ok=True)
        data.write_text("".join(f"{prefix}\n" for prefix in prefixes), encoding="utf-8")

    def add(self, rel: str) -> None:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("def test_x() -> None:\n    pass\n", encoding="utf-8")
        _git(self.root, "add", rel)

    def remove(self, rel: str) -> None:
        _git(self.root, "rm", "-q", "-f", rel)

    def check(self) -> int:
        return gen.main(["--check"], repo_root=self.root)

    def regenerate(self) -> int:
        return gen.main([], repo_root=self.root)

    def roots(self) -> list[str]:
        return _generated_roots(self.pyproject.read_text())


@pytest.fixture
def checkout(tmp_path: Path) -> _Checkout:
    return _Checkout(tmp_path)


def test_moving_a_tests_directory_makes_the_check_fail_until_the_generator_runs(
    checkout: _Checkout,
) -> None:
    checkout.owe("gateway/routers")
    checkout.add("gateway/routers/tests/test_a.py")
    assert checkout.check() == 1
    assert checkout.regenerate() == 0
    assert checkout.check() == 0
    assert checkout.roots() == ["gateway/routers/tests"]

    # meiva:note
    # A test moves into another owing root: the region is stale until the script runs.
    checkout.owe(*_OWING)
    checkout.add("meiva_builtins/skills/integrations/web-ai/scripts/tests/test_b.py")
    assert checkout.check() == 1
    assert checkout.roots() == ["gateway/routers/tests"]  # --check writes nothing
    assert checkout.regenerate() == 0
    assert checkout.check() == 0
    assert checkout.roots() == [
        "gateway/routers/tests",
        "meiva_builtins/skills/integrations/web-ai/scripts/tests",
    ]


