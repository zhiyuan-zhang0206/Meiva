# meiva:note
# A throwaway repository whose data file two branches change from the same base.
class _Branches:
    def __init__(self, root: Path, attributes: str) -> None:
        self.root = root
        self.data = root / gen.OWING_ANY_FILE
        root.mkdir(exist_ok=True)
        _git(root, "init", "-q", "--initial-branch=main")
        (root / ".gitattributes").write_text(attributes, encoding="utf-8")
        self.data.parent.mkdir(parents=True)
        self.data.write_text("base/agents\nbase/lm\n", encoding="utf-8")
        _git(root, "add", "-A")
        _git(root, "commit", "-q", "-m", "base")

    def branch(self, name: str, content: str) -> None:
        _git(self.root, "checkout", "-q", "-b", name, "main")
        self.data.write_text(content, encoding="utf-8")
        _git(self.root, "commit", "-q", "-am", name)

    def merge(self, other: str) -> None:
        _git(self.root, "merge", "-q", "--no-edit", other)

    def prefixes(self) -> tuple[str, ...]:
        return gen.parse_owing_any(self.data.read_text(encoding="utf-8"))


# meiva:note
# Neighbors in the sorted list: both branches insert between the same two lines, which git cannot
# order without help. Without the repository's attribute that is a conflict; with it both lines stay.
def test_two_branches_adding_neighboring_prefixes_merge_only_with_the_union_attribute(
    tmp_path: Path,
) -> None:
    attributes = (_REPO_ROOT / ".gitattributes").read_text(encoding="utf-8")
    plain = _Branches(tmp_path / "plain", "* text=auto eol=lf\n")
    union = _Branches(tmp_path / "union", attributes)
    for repo in (plain, union):
        repo.branch("one", "base/agents\nbase/config\nbase/lm\n")
        repo.branch("two", "base/agents\nbase/host\nbase/lm\n")
        _git(repo.root, "checkout", "-q", "one")

    with pytest.raises(subprocess.CalledProcessError):
        plain.merge("two")
    union.merge("two")
    assert union.prefixes() == ("base/agents", "base/config", "base/host", "base/lm")


# meiva:note
# A union merge keeps ours then theirs, so the order of the two lines depends on the direction of
# the merge: the other direction leaves the second prefix out of place, and the reader names it.
def test_a_union_merge_can_leave_a_prefix_out_of_place_and_the_reader_names_it(
    tmp_path: Path,
) -> None:
    repo = _Branches(tmp_path, (_REPO_ROOT / ".gitattributes").read_text(encoding="utf-8"))
    repo.branch("one", "base/agents\nbase/config\nbase/lm\n")
    repo.branch("two", "base/agents\nbase/host\nbase/lm\n")
    _git(repo.root, "checkout", "-q", "two")
    repo.merge("one")
