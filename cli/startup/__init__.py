# meiva:note
# What `meiva init` and `meiva start` decide before and after their effects, as values.
#
# `log_sinks` says which verbs open the loguru sinks a service process has,
# `settings_failure` words an unconfigured home's Settings failure, `service_path` chooses
# the host tool directories a new home declares, and `outcome` says what a finished start
# owes the boot unit and the boot scheduler. The shells (`cli.init_intent`,
# `cli.start_intent`, `cli.main`) read the environment, the clock and the files, and execute
# what these modules return.
